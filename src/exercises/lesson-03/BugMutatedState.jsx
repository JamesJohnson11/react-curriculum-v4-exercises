/*
  BUG #2 — State Issue

  This component displays a count and updates it when the button is clicked.
  However, the way the count is being changed causes the component to behave
  incorrectly.
*/

import { useState } from 'react';
export default function BugMutatedState() {
  let [count, setCount] = useState(0);

  function handleAdd() {
    setCount((previousCount) => previousCount + 1);
  }

  return (
    <div>
      <p>Bug 2 Count: {count}</p>
      <button onClick={handleAdd}>Add 1</button>
    </div>
  );
}

// Explanation:
// Refectored the handleAdd function to use functional updating of setCount, which takes the previous state as an argument.
// This ensures that the count is updated correctly even if multiple updates are queued.
// Previously the count was being updated directly, which can lead to unexpected behavior in React's state management due to state staleness.
